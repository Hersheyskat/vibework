"use client";

import Link from "next/link";
import type { PublicGame } from "./types";

export function ProgressPane({
  game,
  scoring,
  onScore,
  onGo,
}: {
  game: PublicGame;
  scoring: boolean;
  onScore: (rescore?: boolean) => void;
  onGo: (view: string) => void;
}) {
  const F = game.feedback;

  if (!F) {
    return (
      <div className="pane">
        <h1>Your practice day</h1>
        <p className="sub">
          {game.role} at {game.company.name} · A score, what you practised, and
          how to get better.
        </p>
        <div className="empty">
          <h2>Not scored yet</h2>
          <p>
            {game.dayOver
              ? "Your work is in. Get your practice score."
              : "Finish today's tasks, then come back for your score, the expected answers, and what to read and watch."}
          </p>
          <div className="row">
            {game.dayOver ? (
              <button
                type="button"
                className="btn"
                disabled={scoring}
                onClick={() => onScore(false)}
              >
                {scoring ? "Scoring…" : "Score my day"}
              </button>
            ) : (
              <button
                type="button"
                className="btn"
                onClick={() => onGo("tasks")}
              >
                Go to tasks
              </button>
            )}
          </div>
        </div>
      </div>
    );
  }

  const names = game.skills.map((s) => s.name);
  const scoreMap = Object.fromEntries(
    F.scores.map((s) => [s.skill, s]),
  );

  return (
    <div className="pane">
      <h1>Your practice day</h1>
      <p className="sub">
        {game.role} at {game.company.name}. A score, what you practised, and how
        to get better.
      </p>

      <div className="overview">
        <div className="big">
          <span className="practice">{F.practiceLabel}</span>
          <div className="n">
            <span>{F.total}</span>
            <small>/ 30</small>
          </div>
        </div>
        <div className="verdict">{F.verdict}</div>
      </div>
      <p className="hint" style={{ marginTop: 10 }}>
        This day was generated by AI and scored by AI. Scores are coaching
        feedback and can vary between runs; they are not an assessment an
        employer should rely on.
      </p>

      <h2 style={{ marginTop: 22 }}>Skills</h2>
      <div className="skillgrid">
        {names.map((k) => {
          const row = scoreMap[k];
          const n = row?.score ?? 0;
          return (
            <div className="skillcard" key={k}>
              <div className="skilltop">
                <b>{k}</b>
                <span>
                  {n}/5
                </span>
              </div>
              <div className="skillbar">
                <i style={{ width: `${(n / 5) * 100}%` }} />
              </div>
              <p className="hint">{row?.evidence || ""}</p>
            </div>
          );
        })}
      </div>

      {F.strengths.length ? (
        <>
          <h2 style={{ marginTop: 22 }}>Strengths</h2>
          <ul className="bullets">
            {F.strengths.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        </>
      ) : null}
      {F.improve.length ? (
        <>
          <h2 style={{ marginTop: 16 }}>Gaps</h2>
          <ul className="bullets">
            {F.improve.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        </>
      ) : null}

      <h2 style={{ marginTop: 22 }}>Your answer vs expected</h2>
      {game.tasks.map((t) => {
        const gap =
          F.tasks.find((x) => x.task === t.title)?.gap ||
          "";
        return (
          <details className="tfb" key={t.id}>
            <summary>
              <b>{t.title}</b>
              <span className="hint">{gap}</span>
            </summary>
            <div className="cmp">
              <div>
                <div className="k">Your answer</div>
                <div className="submitted">
                  {t.submission || "(not done)"}
                </div>
              </div>
              <div>
                <div className="k">Expected answer</div>
                <div className="submitted ideal">
                  {t.expectedAnswer || ""}
                </div>
              </div>
            </div>
          </details>
        );
      })}

      {F.missed.length ? (
        <>
          <h2 style={{ marginTop: 22 }}>Clues you missed</h2>
          <ul className="bullets">
            {F.missed.map((m) => (
              <li key={m}>{m}</li>
            ))}
          </ul>
        </>
      ) : null}

      {game.learning.length ? (
        <>
          <h2 style={{ marginTop: 22 }}>Read or watch</h2>
          <p className="sub">
            Picked for your lower scores. Links open a search so you can check
            the source yourself.
          </p>
          <div className="lib">
            {game.learning.flatMap((block) =>
              block.items.map((item) => (
                <a
                  key={`${block.skill}-${item.title}`}
                  className="libcard"
                  href={`https://www.google.com/search?q=${encodeURIComponent(item.search || item.title)}`}
                  target="_blank"
                  rel="noreferrer"
                >
                  <span className="hint">{item.type}</span>
                  <b>{item.title}</b>
                  <small>
                    {item.by}
                    {item.why ? ` · ${item.why}` : ""}
                  </small>
                </a>
              )),
            )}
          </div>
        </>
      ) : null}

      {game.drill ? (
        <div className="drill">
          <b>Drill</b>
          <p style={{ margin: "6px 0 0" }}>{game.drill}</p>
        </div>
      ) : null}

      {game.seniorView ? (
        <div className="drill" style={{ marginTop: 18 }}>
          <b>How a senior would see today</b>
          <p style={{ margin: "6px 0 0" }}>{game.seniorView}</p>
        </div>
      ) : null}

      <div className="drill" style={{ marginTop: 18 }}>
        <b>Get your full debrief.</b> {game.support.mentor.name}, your mentor,
        reviews your chats: what you did right, improvement areas quoting your
        words, the right approach, and exercises.
        <div className="row" style={{ marginTop: 10 }}>
          <button
            type="button"
            className="btn"
            onClick={() => onGo("chat:mentor")}
          >
            Get my debrief
          </button>
        </div>
      </div>

      <div className="row" style={{ marginTop: 24 }}>
        <button
          type="button"
          className="btn ghost"
          disabled={scoring}
          onClick={() => onScore(true)}
        >
          Re-score
        </button>
        <Link className="btn ghost" href="/">
          Try another job
        </Link>
        <Link className="btn ghost" href="/me">
          My days
        </Link>
      </div>
    </div>
  );
}
