export function lev(a: string, b: string): number {
  const aa = a.toLowerCase();
  const bb = b.toLowerCase();
  const d: number[][] = Array.from({ length: aa.length + 1 }, (_, i) => [i]);
  for (let j = 1; j <= bb.length; j++) d[0]![j] = j;
  for (let i = 1; i <= aa.length; i++) {
    for (let j = 1; j <= bb.length; j++) {
      d[i]![j] = Math.min(
        d[i - 1]![j]! + 1,
        d[i]![j - 1]! + 1,
        d[i - 1]![j - 1]! + (aa[i - 1] === bb[j - 1] ? 0 : 1),
      );
    }
  }
  return d[aa.length]![bb.length]!;
}

export function reEsc(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
